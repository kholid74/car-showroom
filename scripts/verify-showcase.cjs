const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.QA_BASE || 'http://127.0.0.1:5173'
const data = require('../src/data/dataset.json')
;(async () => {
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    fs.mkdirSync('.qa', { recursive: true })
    page.setDefaultTimeout(15000)
    const shot = async name => { await page.screenshot({ path: `.qa/updated-${name}.png` }); console.log('Screenshot:', name) }
    await page.goto(base + '/login')
    await page.evaluate(() => document.fonts.ready)
    await shot('login')
    await page.getByRole('button', { name: /Owner & manajemen/ }).click()
    await page.waitForURL(base + '/')
    await page.getByRole('heading', { name: 'Bisnis Anda, dalam satu pandangan.' }).waitFor()
    await shot('dashboard')
    assert.match(await page.locator('main').innerText(), /1 booking mendekati kadaluarsa/)
    for (const [name, route] of [['inventory', '/inventory'], ['vehicle', '/inventory/VH-2026-0001'], ['catalog', '/katalog'], ['catalog-detail', '/katalog/VH-2026-0030']]) {
      await page.goto(base + route)
      await page.locator('main img').first().waitFor()
      await page.waitForFunction(() => [...document.querySelectorAll('main img')].filter(i => i.loading !== 'lazy' || i.getBoundingClientRect().top < innerHeight).every(i => i.complete && i.naturalWidth > 0))
      await shot(name)
    }
    await page.goto(base + '/')
    await page.getByRole('link', { name: 'Lihat katalog publik' }).click()
    assert.equal(page.context().pages().length, 1, 'katalog harus memakai tab/sesi yang sama')
    assert.doesNotMatch(await page.locator('main').innerText(), /Mulai Rp0\b/)
    await page.locator('main a[href^="/katalog/VH-"]').first().click()
    const vehicleId = new URL(page.url()).pathname.split('/').pop()
    await page.getByLabel('Nama', { exact: true }).fill('Uji Showcase')
    await page.getByLabel('Nomor telepon', { exact: true }).fill('081200000000')
    await page.getByRole('button', { name: 'Ajukan minat pada unit ini' }).click()
    await page.goto(base + '/crm?q=Uji%20Showcase')
    const card = page.locator('li').filter({ has: page.getByRole('link', { name: /Uji Showcase/ }) })
    await card.hover()
    await card.getByRole('button', { name: 'Dihubungi', exact: true }).click()
    const contacted = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Dihubungi', exact: true }) })
    assert.match(await contacted.innerText(), /Uji Showcase/, 'lead baru harus benar-benar pindah kolom')
    await page.getByRole('link', { name: /Uji Showcase/ }).click()
    await page.getByRole('button', { name: 'Buat booking', exact: true }).click()
    await page.getByLabel('Harga kesepakatan (Rp)', { exact: false }).fill('80000000')
    await page.getByLabel('DP diterima (Rp)', { exact: false }).fill('5000000')
    await page.getByRole('dialog').getByRole('button', { name: 'Buat booking', exact: true }).click()
    await page.goto(base + '/booking?q=Uji%20Showcase')
    await page.getByRole('button', { name: /Catat penjualan/ }).click()
    assert.equal(await page.getByLabel('Harga jual final (Rp)', { exact: false }).inputValue(), '80000000')
    await page.getByRole('button', { name: 'Catat penjualan', exact: true }).click()
    await page.goto(base + '/inventory/' + vehicleId)
    const detail = await page.locator('main').innerText()
    assert.match(detail, /TERJUAL|Terjual/)
    assert.match(detail, /Uji Showcase/)
    assert.match(detail, /Booking/)
    const state = await page.evaluate(() => JSON.parse(sessionStorage.getItem('car-showroom-sesi-demo')).state)
    const booking = state.bookingBaru.find(b => b.customerNama === 'Uji Showcase')
    const sale = state.penjualanBaru.find(s => s.vehicleId === booking.vehicleId)
    assert.equal(state.tahapLead[booking.leadId], 'WON')
    assert.equal(sale.customerId, booking.customerId)
    assert.equal(sale.finalPrice, 80000000)
    assert.ok(state.bookingSelesai.includes(booking.id))
    await page.goto(base + '/booking?q=Uji%20Showcase')
    assert.match(await page.locator('main').innerText(), /Selesai|SELESAI/)
    for (const width of [768, 375]) {
      await page.setViewportSize({ width, height: 900 })
      for (const route of ['/', '/inventory', '/inventory/' + vehicleId, '/katalog']) {
        await page.goto(base + route)
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${route} overflow at ${width}`)
      }
      await shot('catalog-' + width)
    }
    for (const v of data.vehicles) {
      if (/\b(AT|CVT)\b/.test(v.variant)) assert.equal(v.transmisi, 'AT', v.id)
      if (/\bMT\b/.test(v.variant)) assert.equal(v.transmisi, 'MT', v.id)
    }
    assert.deepEqual(errors, [])
    console.log('LULUS: foto, katalog satu sesi, inquiry → CRM → booking → penjualan, identitas pelanggan, timeline, transmisi, dan viewport desktop/tablet/mobile.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
